const DICTS = { sk: SK, en: EN };
let current = 'sk';

export function setLang(l) {
  current = DICTS[l] ? l : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export function lang() {
  return current;
}

export function t(key, vars = {}) {
  const s = DICTS[current][key] ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined && vars[k] !== null ? vars[k] : ''));
}

/** "5 dní", "1 deň", "3 dni" / "5 days". */
export function days(n) {
  const a = Math.abs(n);
  let unit;
  if (current === 'sk') unit = a === 1 ? t('day.1') : a >= 2 && a <= 4 ? t('day.2') : t('day.5');
  else unit = a === 1 ? t('day.1') : t('day.5');
  return `${a} ${unit}`;
}
